export function t(locale: Locale, key: string): string {
  return DICT[locale]?.[key] ?? DICT.nl[key] ?? key;
}

// Bouw een taal-bewuste URL. NL blijft op de root (geen prefix),
// EN en DE krijgen /en resp. /de ervoor.
export function localeHref(locale: Locale, href: string): string {
  if (locale === "nl" || !href.startsWith("/")) return href;
  if (href === "/") return `/${locale}`;
  return `/${locale}${href}`;
}

export function stripLocale(pathname: string): { locale: Locale; rest: string } {
  const seg = pathname.split("/")[1];
  if (seg === "en" || seg === "de") {
    const rest = pathname.slice(seg.length + 1) || "/";
    return { locale: seg, rest };
  }
  return { locale: "nl", rest: pathname };
}
